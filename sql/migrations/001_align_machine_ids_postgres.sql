-- Migration des données existantes (PostgreSQL, base source).
-- Les anciennes versions du simulateur utilisaient MACHINE_0001..MACHINE_0005,
-- alors que la table machines contient MACHINE_01..MACHINE_20.
-- Ce script renomme ces identifiants puis ajoute la clé étrangère manquante.
-- Faire une sauvegarde avant de l'exécuter.

BEGIN;

UPDATE metadata
SET machine_id = 'MACHINE_' || RIGHT(machine_id, 2)
WHERE machine_id ~ '^MACHINE_00[0-9]{2}$';

ALTER TABLE metadata
    ADD CONSTRAINT metadata_machine_id_fkey
    FOREIGN KEY (machine_id) REFERENCES machines(machine_id);

CREATE INDEX IF NOT EXISTS idx_metadata_machine_time
    ON metadata (machine_id, measured_at);

ALTER TABLE maintenance ALTER COLUMN maintenance_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('maintenance', 'maintenance_id'), (SELECT COALESCE(MAX(maintenance_id), 1) FROM maintenance));

COMMIT;
